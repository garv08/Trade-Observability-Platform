"""Regenerate docs/indicators.md and docs/strategies.md from the live catalogs.

Run from the repository root:  python scripts/generate_catalog_docs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from top.indicators import SECTIONS, catalog as indicator_catalog  # noqa: E402
from top.strategies import catalog as strategy_catalog  # noqa: E402

STRATEGY_ORDER = ["Trend", "Breakout", "Trend reversal", "Harmonics", "@neurotrader888", "@UnbiasedTradingGoshawk",
                  "Oscillator", "Mean reversion", "Price action", "Volume"]


def _params(params):
    if not params:
        return "—"
    return ", ".join(f"{p['label']} `{p['default']}` ({p['min']}–{p['max']})" for p in params)


def _anchor(text):
    return "".join(ch for ch in text.lower().replace(" ", "-") if ch.isalnum() or ch == "-")


def indicators_md():
    items = indicator_catalog()
    lines = [
        "# Indicator catalog",
        "",
        f"All **{len(items)}** studies in TOP, grouped as they appear in the left panel. "
        "*Overlay* studies draw on the price chart; *Pane* studies open their own panel below it. "
        "Every setting can be changed under **On the chart**; studies with a period also offer quick presets and **+ Another**.",
        "",
        "> Generated by `python scripts/generate_catalog_docs.py`. Do not edit by hand.",
        "",
        "| Section | Studies |",
        "| --- | --- |",
    ]
    for section in SECTIONS:
        count = sum(1 for item in items if item["section"] == section)
        lines.append(f"| [{section}](#{_anchor(section)}) | {count} |")
    for section in SECTIONS:
        rows = [item for item in items if item["section"] == section]
        lines += ["", f"## {section}", "", "| ID | Name | Where | Outputs | Settings (default, range) |", "| --- | --- | --- | --- | --- |"]
        for item in rows:
            where = "Overlay" if item["pane"] == "price" else "Pane"
            lines.append(f"| `{item['id']}` | {item['name']} | {where} | {', '.join(item['outputs'])} | {_params(item['params'])} |")
    return "\n".join(lines) + "\n"


def strategies_md():
    items = strategy_catalog()
    sections = [s for s in STRATEGY_ORDER if any(i["section"] == s for i in items)]
    sections += sorted({i["section"] for i in items} - set(sections))
    lines = [
        "# Strategy catalog",
        "",
        f"All **{len(items)}** backtestable strategies. Every rule is **long or flat** on daily bars: the signal is read at the close "
        "and filled at the next session's open, with costs charged on entry and exit. Run any of them on one stock (**Run backtest**) "
        "or across a universe (**Backtest universe**: the Nifty 50, or the most traded ETFs or BSE stocks).",
        "",
        "> Generated by `python scripts/generate_catalog_docs.py`. Do not edit by hand.",
        "",
        "| Group | Strategies |",
        "| --- | --- |",
    ]
    for section in sections:
        count = sum(1 for item in items if item["section"] == section)
        lines.append(f"| [{section}](#{_anchor(section)}) | {count} |")
    for section in sections:
        rows = [item for item in items if item["section"] == section]
        lines += ["", f"## {section}", ""]
        if section.startswith("@"):
            lines += [f"Adapted from the YouTube channel {section}. Sources, confidence, and adaptations are in [creators.md](creators.md).", ""]
        lines += ["| ID | Name | Rule | Settings (default, range) |", "| --- | --- | --- | --- |"]
        for item in rows:
            rule = item["blurb"].replace("|", "\\|")
            if item.get("confidence"):
                rule += f" *(confidence {item['confidence']})*"
            lines.append(f"| `{item['id']}` | {item['name']} | {rule} | {_params(item['params'])} |")
    return "\n".join(lines) + "\n"


def main():
    docs = ROOT / "docs"
    (docs / "indicators.md").write_text(indicators_md(), encoding="utf-8")
    (docs / "strategies.md").write_text(strategies_md(), encoding="utf-8")
    print("wrote docs/indicators.md and docs/strategies.md")


if __name__ == "__main__":
    main()
